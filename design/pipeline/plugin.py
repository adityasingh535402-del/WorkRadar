"""Bundle every captured screen spec + the renderer into a Figma development plugin.

Output: <repo>/design/figma-plugin/{manifest.json, code.js, README.md}
Run inside Figma desktop: Plugins → Development → Import plugin from manifest…
"""
import glob, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = sys.argv[1] if len(sys.argv) > 1 else os.path.abspath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(REPO, 'design', 'figma-plugin')
os.makedirs(OUT, exist_ok=True)

chunks = []
for fn in sorted(glob.glob(os.path.join(HERE, 'calls', '*.js'))):
    first = open(fn, encoding='utf-8').readline()
    m = re.match(r'const S = (.*);\s*$', first)
    assert m, fn
    chunks.append(json.loads(m.group(1)))

render = open(os.path.join(HERE, 'render.js'), encoding='utf-8').read()
# The MCP renderer ends with a top-level `return {...}`; inside a function that is exactly what we want.

COVER = r"""
async function buildCover() {
  const NAME = '00 · Cover & design system';
  const old = figma.currentPage.findChild((x) => x.type === 'FRAME' && x.name === NAME);
  if (old) old.remove();
  const fam = ['Barlow', 'Barlow Semi Condensed', 'Barlow Condensed'];
  for (const f of fam) for (const s of ['Regular', 'Medium', 'SemiBold', 'Bold']) { try { await figma.loadFontAsync({ family: f, style: s }); } catch (e) {} }
  const hex = (h) => ({ r: parseInt(h.slice(1, 3), 16) / 255, g: parseInt(h.slice(3, 5), 16) / 255, b: parseInt(h.slice(5, 7), 16) / 255 });
  const frame = figma.createFrame();
  frame.name = NAME; frame.resize(1440, 320); frame.x = 0; frame.y = -420;
  frame.fills = [{ type: 'SOLID', color: hex('#0d2a33') }];
  frame.cornerRadius = 24;
  const txt = (s, x, y, size, family, style, color, w) => {
    const t = figma.createText();
    t.fontName = { family, style }; t.characters = s; t.fontSize = size;
    t.fills = [{ type: 'SOLID', color: hex(color) }];
    frame.appendChild(t); t.x = x; t.y = y;
    if (w) { t.resize(w, t.height); t.textAutoResize = 'HEIGHT'; }
    return t;
  };
  txt('WorkRadar', 56, 48, 56, 'Barlow Semi Condensed', 'SemiBold', '#eaf7f3');
  txt('Hi-fi screens · Airtribe Learning Platform · built from the live MVP', 56, 120, 22, 'Barlow', 'Regular', '#8fb4ad');
  txt('Air-traffic-control direction: a dark radar scope as the hero, flight-strip rows, explainable scores. Every screen below is editable layers generated from the running app (DOM → spec → Figma).', 56, 160, 16, 'Barlow', 'Regular', '#a8bdbb', 640);
  const pal = [['Scope', '#0d2a33'], ['Sweep', '#5fe3c8'], ['Flare', '#f5a524'], ['Halt', '#e5484d'], ['Clear', '#2f9e6e'], ['Hold', '#7b7fb8'], ['Ink', '#12282f'], ['Paper', '#eaefee']];
  pal.forEach(([n, c], i) => {
    const x = 780 + (i % 4) * 150, y = 48 + Math.floor(i / 4) * 96;
    const sw = figma.createFrame(); sw.resize(56, 56); sw.cornerRadius = 12;
    sw.fills = [{ type: 'SOLID', color: hex(c) }];
    sw.strokes = [{ type: 'SOLID', color: hex('#ffffff'), opacity: 0.18 }]; sw.strokeWeight = 1;
    frame.appendChild(sw); sw.x = x; sw.y = y; sw.name = n;
    txt(n, x + 66, y + 8, 15, 'Barlow', 'SemiBold', '#eaf7f3');
    txt(c, x + 66, y + 30, 13, 'Barlow', 'Regular', '#8fb4ad');
  });
  txt('Type: Barlow Semi Condensed (headings) · Barlow (body) · Barlow Condensed (refs, scores)', 780, 252, 14, 'Barlow', 'Medium', '#a8bdbb', 600);
  const rows = [['Core flows', 400], ['Interactions & dark mode', 2300], ['Empty & error states', 3500], ['Mobile', 4800]];
  for (const [label, y] of rows) {
    const old2 = figma.currentPage.findChild((x) => x.type === 'TEXT' && x.name === 'Row · ' + label);
    if (old2) old2.remove();
    const t = figma.createText();
    t.fontName = { family: 'Barlow Semi Condensed', style: 'SemiBold' }; t.characters = label; t.fontSize = 40;
    t.fills = [{ type: 'SOLID', color: hex('#12282f') }];
    t.name = 'Row · ' + label; figma.currentPage.appendChild(t); t.x = 0; t.y = y - 90;
  }
}
"""

code = (
    '// Generated by scratchpad/figma/plugin.py. Rebuilds all WorkRadar screens as editable layers.\n'
    'const SPECS = ' + json.dumps(chunks, ensure_ascii=False, separators=(',', ':')) + ';\n'
    'async function build(S) {\n'
    "  if (S.start === 0) { const old = figma.currentPage.findChild((x) => x.type === 'FRAME' && x.name === S.name); if (old) old.remove(); }\n"
    + render + '\n}\n' + COVER + r"""
(async () => {
  try {
    if (figma.currentPage.name === 'Page 1') figma.currentPage.name = 'WorkRadar · Screens';
    let made = 0;
    for (let i = 0; i < SPECS.length; i++) {
      figma.notify(`WorkRadar: building ${SPECS[i].name} (${i + 1}/${SPECS.length})`, { timeout: 1500 });
      const r = await build(SPECS[i]);
      made += r.made;
    }
    await buildCover();
    figma.viewport.scrollAndZoomIntoView(figma.currentPage.children);
    figma.closePlugin(`WorkRadar: ${made} layers across 15 screens + cover`);
  } catch (e) {
    figma.closePlugin('WorkRadar plugin failed: ' + (e && e.message ? e.message : e));
  }
})();
"""
)
open(os.path.join(OUT, 'code.js'), 'w', encoding='utf-8').write(code)
json.dump({
    'name': 'WorkRadar screens',
    'id': 'workradar-screens-local',
    'api': '1.0.0',
    'main': 'code.js',
    'editorType': ['figma'],
    'documentAccess': 'dynamic-page',
    'networkAccess': {'allowedDomains': ['none']},
}, open(os.path.join(OUT, 'manifest.json'), 'w'), indent=2)
print('chunks', len(chunks), 'bytes', len(code))
