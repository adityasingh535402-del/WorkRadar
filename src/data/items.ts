const iso = (now: number, rel: Rel) => new Date(now + rel * 60_000).toISOString();
/** Deadlines land on the quarter hour, like real ones do. */
const isoDue = (now: number, rel: Rel) => {
  const q = 15 * 60_000;
  return new Date(Math.round((now + rel * 60_000) / q) * q).toISOString();
};

const mapMsgs = (now: number, msgs: SeedMsg[]) => msgs.map((m) => ({ ...m, at: iso(now, m.at) }));

function resolveDetail(now: number, d: SeedDetail): Detail {
  switch (d.kind) {
    case 'thread':
      return { ...d, messages: mapMsgs(now, d.messages) };
    case 'ticket':
    case 'pr':
    case 'issue':
      return { ...d, comments: mapMsgs(now, d.comments) } as Detail;
    case 'email':
      return d;
  }
}

const mockUrl = (s: Seed) => {
  switch (s.source) {
    case 'jira':
      return `https://jira.example.com/browse/${s.ref}`;
    case 'github': {
      const d = s.detail as { repo?: string; number?: number };
      return d.repo ? `https://github.example.com/${d.repo}/pull/${d.number ?? ''}` : 'https://github.example.com';
    }
    case 'slack':
      return `https://slack.example.com/archives/${s.ref.replace(/[^a-z0-9-]/gi, '')}`;
    case 'email':
      return 'https://mail.example.com';
  }
};

export function buildItems(now = Date.now()): WorkItem[] {
  return SEEDS.map((s) => {
    const activity: ActivityEvent[] = (s.activity ?? []).map((a) => ({ ...a, at: iso(now, a.at) }));
    if (s.done !== undefined && !activity.some((a) => a.text.includes('done') || a.text.includes('merged'))) {
      activity.push({ at: iso(now, s.done), by: s.assignee ?? s.author, text: s.source === 'github' && s.detail.kind === 'pr' ? 'merged the pull request' : 'marked it done' });
    }
    return {
      id: s.id,
      source: s.source,
      ref: s.ref,
      url: mockUrl(s),
      project: s.project,
      title: s.title,
      summary: s.summary,
      status: s.status,
      priority: s.priority,
      assignee: s.assignee,
      author: s.author,
      createdAt: iso(now, s.created),
      updatedAt: iso(now, s.updated),
      dueAt: s.due !== undefined ? isoDue(now, s.due) : undefined,
      dueLabel: s.dueLabel,
      labels: s.labels ?? [],
      signals: s.signals ?? {},
      blockedBy: s.blockedBy ? { ...s.blockedBy, since: iso(now, s.blockedBy.since) } : undefined,
      related: s.related,
      nextStep: s.next,
      detail: resolveDetail(now, s.detail),
      activity,
      snoozedUntil: s.snoozed !== undefined ? isoDue(now, s.snoozed) : undefined,
      doneAt: s.done !== undefined ? iso(now, s.done) : undefined,
    } satisfies WorkItem;
  });
}
