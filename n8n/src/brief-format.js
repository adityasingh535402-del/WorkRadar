// n8n Code node · "Format for Slack" (Run once for all items)
// Turns the AI brief into a Slack message (mrkdwn). Also usable as an email body.

const res = $input.first().json;
const brief = res.brief || {};
const ingest = $('Get ranked items').first().json;
const byId = new Map((ingest.items || []).map((i) => [i.id, i]));
const roster = new Map((ingest.snapshot.team || []).map((p) => [p.id, p.name]));
const ref = (id) => (byId.get(id) ? `*${byId.get(id).ref}* ${byId.get(id).title}` : id);

const lines = [];
lines.push(`*WorkRadar morning brief* for ${ingest.snapshot.manager.name}`);
lines.push(brief.headline || '');
lines.push('');
lines.push('*Top work for today*');
(brief.topWork || []).forEach((t, i) => lines.push(`${i + 1}. ${ref(t.itemId)}\n    ${t.why}`));
if ((brief.blocked || []).length) {
  lines.push('');
  lines.push("*Who's blocked*");
  brief.blocked.forEach((b) => lines.push(`• ${roster.get(b.personId) || b.personId}: ${b.blockedOn}${b.since ? ` (${b.since})` : ''}\n    ${b.suggestion}`));
}
if ((brief.happened || []).length) {
  lines.push('');
  lines.push('*What happened*');
  brief.happened.slice(0, 4).forEach((h) => lines.push(`• ${h.text}`));
}
lines.push('');
lines.push(`_Generated by ${res.model || 'n8n'} at ${new Date().toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit' })}_`);

return [{ json: { text: lines.join('\n'), brief } }];
